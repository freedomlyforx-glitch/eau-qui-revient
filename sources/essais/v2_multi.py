import asyncio, sys, json
sys.path.insert(0, __import__('os').path.dirname(__file__))
from v2 import *
async def ev(pg, js):
    return await pg.evaluate("(() => { const d = window.__dbg; " + js + " })()")
async def main():
    async with async_playwright() as p:
        b, ctx = await setup(p, 320, 180)
        la, lb = [], []
        ctx.set_default_navigation_timeout(400000)
        A = await page(ctx, la, 'https://jeu.test/?test-local')
        A.set_default_navigation_timeout(400000)
        B = await ctx.new_page(); B.set_default_timeout(400000)
        B.on('pageerror', lambda e: lb.append(f'[pageerror] {e}'))
        await B.route('**/*', route)
        await B.goto('https://jeu.test/?test-local', timeout=400000)
        await A.wait_for_timeout(5000)
        await ev(A, "d.PROFILE.nom='Alice'; d.PROFILE.type='grenouille'; d.PROFILE.langue='fr'; d.chooseDevice('pc'); d.PREP.monde='ligne'; d.PREP.ouvert=true; d.PREP.regle='bagarre'; d.startGame();")
        await A.wait_for_timeout(1500)
        await ev(B, "d.PROFILE.nom='Bob'; d.PROFILE.type='axolotl'; d.PROFILE.couleur='#9fd4ff'; d.PROFILE.langue='en'; d.chooseDevice('pc');")
        await B.click('#mLigne')
        await B.wait_for_timeout(5000)
        lst = await B.inner_text('#listeServeurs')
        print('liste vue par Bob:', lst.replace('\n', ' | '))
        await B.click('#listeServeurs button')
        await B.wait_for_timeout(4000)
        print('A:', await ev(A, "return JSON.stringify({peers:[...d.NET.peers.values()].map(p=>p.nom), host:d.NET.isHost(), rule:d.NET.rule})"))
        print('B:', await ev(B, "return JSON.stringify({peers:[...d.NET.peers.values()].map(p=>p.nom), host:d.NET.isHost(), rule:d.NET.rule, srv:d.NET.server.nom})"))
        await ev(A, "d.P.pos.set(0,0,60); d.P.yaw=0; d.P.pitch=0;")
        await ev(B, "d.P.pos.set(1.5,0,57); d.P.yaw=Math.PI; d.P.pitch=0;")
        await A.wait_for_timeout(4000)
        await A.screenshot(path=BASE + '/tests/m_A.png'); await B.screenshot(path=BASE + '/tests/m_B.png')
        await ev(A, "d.destroyPanel(d.panels[10], false, null)")
        await A.wait_for_timeout(1500)
        print('panneau 10 chez B:', await ev(B, "return d.panels[10].alive"))
        await ev(A, "d.breakPiece ? 0 : 0; const p = d.DESTR.pieces[5]; p.hp = 0.5; const o = new THREE.Vector3(p.x, p.y + 3, p.z); const dir = new THREE.Vector3(0, -1, 0); d.applyHit({ kind: 'meuble', meuble: p, point: new THREE.Vector3(p.x, p.y, p.z), n: new THREE.Vector3(0,1,0) }, dir, d.WEAPONS[0], 1, false);")
        await ev(A, "const c = d.CARS[0]; d.applyHit({ kind: 'voiture', car: c, point: new THREE.Vector3(c.x, 1, c.z), n: new THREE.Vector3(1,0,0) }, new THREE.Vector3(-1,0,0), d.WEAPONS[0], 1, false); d.JET.has = true; d.JET.thrust = true;")
        await A.wait_for_timeout(2500)
        print('meuble 5 chez B:', await ev(B, "return JSON.stringify({meuble: d.DESTR.pieces[5].alive, alarme: d.CARS[0].alarm > 0, jetA: [...d.NET.peers.values()].map(p => p.av && p.av.jet && p.av.jet.visible)})"))
        # discussion
        await ev(B, "d.keys.KeyT=false;")
        await B.keyboard.press('t')
        await A.wait_for_timeout(2000)
        print('demande chez A visible:', await A.is_visible('#demande'))
        await A.keyboard.press('o')
        await A.wait_for_timeout(1500)
        print('discussion A/B ouvertes:', await A.is_visible('#discussion'), await B.is_visible('#discussion'))
        await ev(B, "document.getElementById('message').value='Hello, nice pool!'; document.getElementById('saisie').requestSubmit();")
        await A.wait_for_timeout(4000)
        print('messages chez A:', (await A.inner_text('#messages')).replace('\n', ' | '))
        await A.screenshot(path=BASE + '/tests/m_chat.png')
        print('logs A', la[:10]); print('logs B', lb[:10])
        await b.close()
asyncio.run(main())
