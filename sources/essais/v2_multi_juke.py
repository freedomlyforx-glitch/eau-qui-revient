import asyncio, sys, json
sys.path.insert(0, __import__('os').path.dirname(__file__))
from v2 import *
async def ev(pg, js):
    return await pg.evaluate("(() => { const d = window.__dbg; " + js + " })()")
ST = "return JSON.stringify({cur: d.JUKE.cur, pos: +(d.JUKE.cur ? (((performance.now() - d.JUKE.t0) / 1000)) : 0).toFixed(2), el: d.JUKE.el ? d.JUKE.el.src.slice(-11) : null, t: d.JUKE.el ? +d.JUKE.el.currentTime.toFixed(2) : null, paused: d.JUKE.el ? d.JUKE.el.paused : null, base: d.MUS.paused, self: d.NET.selfId, host: d.NET.hostId(), peers: [...d.NET.peers.values()].map(p => p.nom)})"
async def main():
    async with async_playwright() as p:
        b, ctx = await setup(p, 320, 180)
        la, lb = [], []
        ctx.set_default_navigation_timeout(400000)
        A = await page(ctx, la, 'https://jeu.test/?test-local')
        A.set_default_navigation_timeout(400000)
        await A.wait_for_timeout(5000)
        await ev(A, "d.PROFILE.nom='Alice'; d.PROFILE.type='grenouille'; d.chooseDevice('pc'); d.PREP.monde='ligne'; d.PREP.ouvert=true; d.PREP.regle='paisible'; d.startGame();")
        await A.wait_for_timeout(1500)
        await ev(A, "d.jukeChoose(2);")
        await A.wait_for_timeout(3000)
        print('A avant B:', await ev(A, ST))
        B = await ctx.new_page(); B.set_default_timeout(400000)
        B.on('pageerror', lambda e: lb.append(f'[pageerror] {e}'))
        B.on('console', lambda m: lb.append(f'[{m.type}] {m.text}') if m.type in ('error','warning') and 'Mixed' not in m.text else None)
        await B.route('**/*', route)
        await B.goto('https://jeu.test/?test-local', timeout=400000)
        await B.wait_for_timeout(3000)
        await ev(B, "d.PROFILE.nom='Bob'; d.PROFILE.type='axolotl'; d.chooseDevice('pc');")
        await B.click('#mLigne')
        await B.wait_for_selector('#listeServeurs button', timeout=400000)
        await B.click('#listeServeurs button')
        await B.wait_for_timeout(8000)
        print('A:', await ev(A, ST))
        print('B (arrivé après):', await ev(B, ST))
        print('jlog B', await ev(B, 'return (d.JUKE.log || []).join(" | ")'))
        print('logs B', lb[:10])
        await ev(A, "d.jukeChoose(4);")
        await A.wait_for_timeout(6000)
        print('A après B1:', await ev(A, ST))
        print('B après B1:', await ev(B, ST))
        print('toast B:', await B.inner_text('#invite'))
        await ev(B, "d.JUKE.at = d.JUKE.boxes[3]; d.jukeChoose(0);")
        await A.wait_for_timeout(5000)
        print('A après arrêt par B:', await ev(A, ST))
        print('B après arrêt:', await ev(B, ST))
        print('toast A:', await A.inner_text('#invite'))
        print('jlog A', await ev(A, 'return (d.JUKE.log || []).join(" | ")'))
        print('jlog B', await ev(B, 'return (d.JUKE.log || []).join(" | ")'))
        print('logs B', [l for l in lb if 'Mixed' not in l][:10])
        await b.close()
asyncio.run(main())
