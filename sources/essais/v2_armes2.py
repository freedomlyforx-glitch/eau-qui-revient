import asyncio, sys, json
sys.path.insert(0, __import__('os').path.dirname(__file__))
from v2 import *
async def ev(pg, js):
    return await pg.evaluate("(() => { const d = window.__dbg; " + js + " })()")
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', headless=True, args=['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist','--use-gl=angle'])
        ctx = await b.new_context(viewport={'width': 640, 'height': 360})
        ctx.set_default_timeout(400000); ctx.set_default_navigation_timeout(400000)
        la, lb = [], []
        A = await ctx.new_page(); A.on('pageerror', lambda e: la.append(str(e))); await A.route('**/*', route)
        await A.goto('https://jeu.test/?test-local'); await A.wait_for_timeout(3000)
        await ev(A, "d.PROFILE.nom='Alice'; d.PROFILE.type='chat'; d.chooseDevice('pc'); d.PREP.monde='ligne'; d.PREP.ouvert=true; d.startGame(); d.setState('pause');")
        B = await ctx.new_page(); B.on('pageerror', lambda e: lb.append(str(e))); await B.route('**/*', route)
        await B.goto('https://jeu.test/?test-local'); await B.wait_for_timeout(3000)
        await ev(B, "d.PROFILE.nom='Bob'; d.chooseDevice('pc');")
        await B.evaluate("document.getElementById('mLigne').click()")
        await B.wait_for_selector('#listeServeurs button', timeout=300000)
        await B.evaluate("document.querySelector('#listeServeurs button').click()")
        await B.wait_for_timeout(5000)
        await ev(A, "d.setState('jeu'); d.P.pos.set(1.2, 0, 60); d.P.yaw = Math.PI + 0.6; d.P.pitch = 0.1; d.switchWeapon(2);")
        await ev(B, "d.P.pos.set(0, 0, 63.5); d.P.yaw = 0.25; d.P.pitch = -0.05;")
        await A.wait_for_timeout(6000)
        print('B voit A:', await ev(B, "const p = [...d.NET.peers.values()][0]; return JSON.stringify({w: p.w, x: p.x, z: p.z, vis: p.av && p.av.g.visible, arme: p.av && p.av.w})"))
        await B.screenshot(path=BASE + '/tests/m_arme_autre.png')
        await ev(A, "d.switchWeapon(1); d.WPN.firing = true;")
        await A.wait_for_timeout(5000)
        await B.screenshot(path=BASE + '/tests/m_arme_autre2.png')
        print('B voit A (2):', await ev(B, "const p = [...d.NET.peers.values()][0]; return JSON.stringify({w: p.w, flags: p.flags, arme: p.av && p.av.w})"))
        await ev(A, "d.WPN.firing = false; d.P.pos.set(-104.2, 0.34, -4.3); d.P.yaw = Math.PI / 2;")
        await ev(B, "d.P.pos.set(-98.2, 0.34, -1.5); d.P.yaw = Math.atan2(-(-104.2 + 98.2), -(-4.3 + 1.5)) ; d.P.pitch = -0.05;")
        await A.wait_for_timeout(4000)
        await ev(A, "d.enterPC();")
        await B.wait_for_timeout(4000)
        print('animation entree:', await ev(B, "const p = [...d.NET.peers.values()][0]; return JSON.stringify({anim: p.pcAnim && p.pcAnim.k, inPC: p.inPC})"))
        await ev(B, "d.step(12, 0.05);")
        await B.wait_for_timeout(2500)
        await B.screenshot(path=BASE + '/tests/m_pc_entree.png')
        await ev(A, "d.step(40, 0.05);")
        await A.wait_for_timeout(3000)
        await ev(A, "d.exitPC();")
        await A.wait_for_timeout(1500)
        await B.wait_for_timeout(3000)
        print('animation sortie:', await ev(B, "const p = [...d.NET.peers.values()][0]; return JSON.stringify({anim: p.pcAnim && p.pcAnim.k, inPC: p.inPC})"))
        await ev(B, "d.step(10, 0.05);")
        await B.wait_for_timeout(2500)
        await B.screenshot(path=BASE + '/tests/m_pc_sortie.png')
        print('erreurs', la[:5], lb[:5])
        await b.close()
asyncio.run(main())
