import asyncio, sys, json
sys.path.insert(0, __import__('os').path.dirname(__file__))
from v2 import *
async def ev(pg, js):
    return await pg.evaluate("(() => { const d = window.__dbg; " + js + " })()")
async def center(pg, sel):
    return json.loads(await pg.evaluate("(() => { const r = document.querySelector('" + sel + "').getBoundingClientRect(); return JSON.stringify([r.x + r.width / 2, r.y + r.height / 2, r.width]); })()"))
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', headless=True, args=['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist','--use-gl=angle'])
        ctx = await b.new_context(viewport={'width': 800, 'height': 420}, has_touch=True)
        ctx.set_default_timeout(400000); ctx.set_default_navigation_timeout(400000)
        la, lb = [], []
        A = await ctx.new_page(); A.on('pageerror', lambda e: la.append(str(e))); await A.route('**/*', route)
        await A.goto('https://jeu.test/?test-local')
        await A.wait_for_timeout(3000)
        await ev(A, "d.PROFILE.nom='Alice'; d.chooseDevice('pc'); d.PREP.monde='ligne'; d.PREP.ouvert=true; d.PREP.regle='paisible'; d.startGame();")
        await ev(A, "d.setState('pause');")
        B = await ctx.new_page(); B.on('pageerror', lambda e: lb.append(str(e))); await B.route('**/*', route)
        await B.goto('https://jeu.test/?test-local')
        await B.wait_for_timeout(3000)
        await ev(B, "d.PROFILE.nom='Bob'; d.chooseDevice('mobile');")
        await B.evaluate("document.getElementById('mLigne').click()")
        await B.wait_for_timeout(6000)
        await B.wait_for_selector('#listeServeurs button', timeout=300000)
        await B.evaluate("document.querySelector('#listeServeurs button').click()")
        await B.wait_for_timeout(6000)
        await ev(A, "d.setState('jeu'); d.P.pos.set(0,0,60); d.P.yaw=Math.PI;")
        await ev(B, "d.P.pos.set(0,0,63); d.P.yaw=0;")
        await B.wait_for_timeout(5000)
        print('B pairs:', await ev(B, "return JSON.stringify({peers:[...d.NET.peers.values()].map(p=>[p.nom, p.x, p.z]), btn: !document.getElementById('tDiscute').hidden, txt: document.getElementById('tDiscute').textContent})"))
        x, y, w = await center(B, '#tDiscute')
        print('bouton', x, y, w, await B.evaluate(f"(() => {{ const e = document.elementFromPoint({x}, {y}); return e && (e.id || e.className); }})()"))
        await B.touchscreen.tap(x, y)
        await A.wait_for_timeout(5000)
        print('demande chez A:', await A.is_visible('#demande'))
        await A.keyboard.press('o')
        await B.wait_for_timeout(5000)
        print('discussion B ouverte:', await B.is_visible('#discussion'), 'texte bouton:', await B.evaluate("document.getElementById('tDiscute').textContent"))
        x, y, w = await center(B, '#tDiscute')
        print('bouton visible au toucher:', await B.evaluate(f"(() => {{ const e = document.elementFromPoint({x}, {y}); return e && (e.id || e.className); }})()"))
        await B.touchscreen.tap(x, y)
        await B.wait_for_timeout(1500)
        print('saisie active chez B:', await B.evaluate("document.activeElement && document.activeElement.id"))
        await B.keyboard.type('coucou depuis la tablette')
        bx, by, bw = await center(B, '#saisie button')
        await B.touchscreen.tap(bx, by)
        await A.wait_for_timeout(5000)
        print('messages chez A:', (await A.inner_text('#messages')).replace('\n', ' | '))
        await B.screenshot(path=BASE + '/tests/m_chat_tablette.png')
        print('erreurs', la[:5], lb[:5])
        await b.close()
asyncio.run(main())
